package com.example.vibereader.domain.prompt

/**
 * Cleans book text before it is scored or sent to an AI provider.
 *
 * EPUB and PDF extraction routinely leave behind HTML tags, page numbers,
 * illustration placeholders, Project Gutenberg boilerplate, control characters,
 * and runs of blank lines. Those artifacts cost tokens without adding meaning,
 * so every prompt builder and local retriever must run text through here first.
 */
object AiContextSanitizer {

    fun sanitize(raw: String): String {
        if (raw.isBlank()) return ""
        val normalized = raw
            .replace("\r\n", "\n")
            .replace('\r', '\n')
            .replace(CONTROL_CHARS, "")
            .replace(HTML_TAG, " ")
            .replace('\u00A0', ' ')
            .replace('\u2007', ' ')
            .replace('\u202F', ' ')
            .replace('\u00AD', ' ')

        val lines = normalized.lineSequence()
            .map(::cleanLine)
            .filter(String::isNotBlank)
            .filterNot(::isArtifactLine)
            .toList()

        if (lines.isEmpty()) return ""
        return lines
            .joinToString("\n")
            .replace(BLANK_LINES, "\n\n")
            .trim()
    }

    /**
     * Sanitizes one snippet and caps it at [maxChars] without slicing through
     * the middle of a word or sentence when a reasonable boundary exists.
     */
    fun sanitizeSnippet(raw: String, maxChars: Int): String {
        val clean = sanitize(raw)
        if (clean.isEmpty()) return ""
        return truncateAtBoundary(clean, maxChars.coerceAtLeast(1))
    }

    fun truncateAtBoundary(raw: String, maxChars: Int): String {
        val limit = maxChars.coerceAtLeast(1)
        val text = raw.trim()
        if (text.length <= limit) return text

        val candidate = text.substring(0, limit)
        val sentenceBoundary = (limit * 0.5f).toInt()
        val minimumBoundary = (limit * 0.6f).toInt()
        val sentenceBreak = candidate.lastIndexOfAny(
            charArrayOf('.', '!', '?', '\n'),
        ).takeIf { it >= sentenceBoundary }
        if (sentenceBreak != null) {
            return candidate.substring(0, sentenceBreak + 1).trim()
        }
        val wordBreak = candidate.lastIndexOf(' ')
            .takeIf { it >= minimumBoundary }
        if (wordBreak != null) {
            return candidate.substring(0, wordBreak).trim()
        }
        return candidate.trim()
    }

    /** Collapses every run of whitespace into a single space. */
    fun oneLine(raw: String): String = sanitize(raw)
        .replace('\n', ' ')
        .replace(INLINE_WHITESPACE, " ")
        .trim()

    private fun cleanLine(line: String): String = line
        .replace(INLINE_WHITESPACE, " ")
        .trim()

    private fun isArtifactLine(line: String): Boolean {
        if (line.isEmpty()) return true
        if (PAGE_NUMBER.matches(line)) return true
        if (ROMAN_PAGE_NUMBER.matches(line)) return true
        if (ARTIFACT_LINE.matches(line)) return true
        if (GUTENBERG_ARTIFACT.containsMatchIn(line)) return true
        if (line.length <= MAX_PUNCTUATION_LINE && PUNCTUATION_ONLY.matches(line)) return true
        return false
    }

    private const val MAX_PUNCTUATION_LINE = 12

    private val CONTROL_CHARS = Regex("[\\u0000-\\u0008\\u000B\\u000C\\u000E-\\u001F\\u007F]")
    private val HTML_TAG = Regex("<[^>]{1,200}>")
    private val INLINE_WHITESPACE = Regex("[\\t\\x0B\\f\\r ]+")
    private val BLANK_LINES = Regex("\\n(?:[ \\t]*\\n)+")
    private val PAGE_NUMBER = Regex(
        """^\s*(?:page|p\.?)\s*\d{1,4}\s*(?:of\s*\d{1,4})?\s*$""",
        RegexOption.IGNORE_CASE,
    )
    private val ROMAN_PAGE_NUMBER = Regex("""^\s*[ivxlcdm]{1,7}\s*$""", RegexOption.IGNORE_CASE)
    private val ARTIFACT_LINE = Regex(
        """^\s*(?:[*_=~#-]{2,}|\[(?:image|illustration|figure|photo|picture)\b[^\]]*]|\((?:image|illustration|figure|photo|picture)[^)]*\))\s*$""",
        RegexOption.IGNORE_CASE,
    )
    private val PUNCTUATION_ONLY = Regex("""^[^\p{L}\p{N}]+$""")
    private val GUTENBERG_ARTIFACT = Regex(
        """^\s*(?:\*\*\*\s*(?:start|end) of|project gutenberg|produced by|transcriber'?s note|generated by)\b.*$""",
        RegexOption.IGNORE_CASE,
    )
}
